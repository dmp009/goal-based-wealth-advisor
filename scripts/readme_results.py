"""Rewrite the README sample-client tables from the engine.

Runs ``build_proposal`` (and ``build_review`` for clients with an existing portfolio) on the
committed snapshot and writes two Markdown tables between the RESULTS markers of README.md.

Usage: python -m scripts.readme_results  (or `make readme`)
"""

from __future__ import annotations

import re
from pathlib import Path

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"
_HOUSEHOLD = {"single": "single", "couple": "couple"}
_WRAPPER = {"av": "assurance-vie", "cto": "CTO"}


def _eur(x: float) -> str:
    return f"€{x:,.0f}"


def _pct(x: float) -> str:
    return f"{x:.1f}%"


def _structured_cell(s: dict) -> str:
    if s.get("included"):
        cell = (
            f"**Included**: {s.get('product_name', s.get('product_id'))}, "
            f"{_eur(s.get('amount_eur', 0))} in {_WRAPPER.get(s.get('wrapper'), s.get('wrapper'))}"
        )
        if "prob_capital_loss_pct" in s:
            cell += f" (simulated probability of capital loss {_pct(s['prob_capital_loss_pct'])})"
        return cell
    reasons = " ".join(s.get("reasons", [])) or "no reason recorded"
    return f"**Excluded**: {reasons}"


def render_clients_table(facts_list: list[dict]) -> str:
    """One row per client from ``proposal_facts`` dicts (pure function, no I/O)."""
    lines = [
        (
            "| Client | Age, household | Risk profile | Goals: target in today's €, year, probability "
            "| Structured product |"
        ),
        "|---|---|:-:|---|---|",
    ]
    for f in facts_list:
        c = f["client"]
        goals = "<br>".join(
            f"{g['label']}: {_eur(g.get('target_today_eur', g['target_nominal_eur']))}, "
            f"{g.get('goal_year', '')}, **{_pct(g['probability_pct'])}**"
            for g in f["goals"]
        )
        cells = [
            c["name"],
            f"{c['age']}, {_HOUSEHOLD.get(c['household'], c['household'])}",
            f"{f['profile']['risk_profile_count']} / 7",
            goals,
            _structured_cell(f["structured"]),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_reviews_table(review_list: list[dict]) -> str:
    """One row per annual review from ``review_facts`` dicts (pure function, no I/O)."""
    lines = [
        (
            "| Client | Period | Time-weighted return | Gain | Rebalancing trades "
            "| Goal probability: at proposal → now |"
        ),
        "|---|---|--:|--:|---|---|",
    ]
    for r in review_list:
        total = r["performance"]["total"]
        n = len(r["trades"])
        if n:
            tt = r["trade_totals"]
            trades = f"{n} ({_eur(tt['sells_eur'])} sold, {_eur(tt['est_tax_eur'])} est. tax)"
        else:
            trades = "0 (all classes inside the band)"
        goals = "<br>".join(
            f"{g['label']}: {_pct(g['probability_before_pct'])} → {_pct(g['probability_now_pct'])}"
            for g in r["goals"]
        )
        cells = [
            r["client"]["name"],
            f"{r['proposal_date']} to {r['as_of']} ({r['months_since_proposal_count']} months)",
            _pct(total["twr_pct"]),
            _eur(total["gain_eur"]),
            trades,
            goals,
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_block(facts_list: list[dict], review_list: list[dict], as_of: str) -> str:
    return "\n".join(
        [
            (
                f"*Generated by `make readme` from the engine on the committed snapshot "
                f"(last price date {as_of}).*"
            ),
            "",
            "**New-client proposals**",
            "",
            render_clients_table(facts_list),
            "",
            "**Annual reviews** (clients with a portfolio opened 18 months earlier)",
            "",
            render_reviews_table(review_list),
        ]
    )


def replace_block(readme: str, block: str) -> str:
    """Replace everything between the RESULTS markers with ``block``."""
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(readme):
        raise ValueError(f"README has no {START} ... {END} block")
    return pattern.sub(lambda _: f"{START}\n{block}\n{END}", readme, count=1)


def collect() -> tuple[list[dict], list[dict], str]:
    from wealthadvisor.clients.models import list_sample_clients
    from wealthadvisor.data.snapshot import load_snapshot
    from wealthadvisor.proposal import build_proposal, proposal_facts
    from wealthadvisor.review.engine import build_review, review_facts

    con = load_snapshot()
    facts, reviews = [], []
    for c in list_sample_clients():
        facts.append(proposal_facts(build_proposal(c, con)))
        if c.original_proposal:
            reviews.append(review_facts(build_review(c, con)))
    return facts, reviews, facts[0]["as_of"] if facts else ""


def main(readme: Path = Path("README.md")) -> None:
    facts, reviews, as_of = collect()
    text = replace_block(readme.read_text(encoding="utf-8"), render_block(facts, reviews, as_of))
    readme.write_text(text, encoding="utf-8")
    print(f"Updated results in {readme} ({len(facts)} clients, {len(reviews)} reviews)")


if __name__ == "__main__":
    main()
